// Builds the Kanakku wordmark as outlined SVG paths (no font dependency) plus the K monogram.
// Run: node scripts/build-logo.mjs
import opentype from 'opentype.js';
import { writeFileSync, mkdirSync } from 'fs';

const font = opentype.loadSync('node_modules/@fontsource/inter/files/inter-latin-600-normal.woff');
const size = 100;
const tracking = -0.035 * size; // tighten slightly for a confident wordmark
const text = 'kanakku';
let x = 0;
const paths = [];
for (const ch of text) {
  const g = font.charToGlyph(ch);
  const p = g.getPath(x, 0, size);
  paths.push(p.toPathData(2));
  x += (g.advanceWidth / font.unitsPerEm) * size + tracking;
}
const bb = (() => {
  const p = font.getPath(text, 0, 0, size);
  return p.getBoundingBox();
})();
// recompute bbox with our tracking by combining glyph paths
let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
x = 0;
for (const ch of text) {
  const g = font.charToGlyph(ch);
  const b = g.getPath(x, 0, size).getBoundingBox();
  minX = Math.min(minX, b.x1); minY = Math.min(minY, b.y1); maxX = Math.max(maxX, b.x2); maxY = Math.max(maxY, b.y2);
  x += (g.advanceWidth / font.unitsPerEm) * size + tracking;
}
const pad = 0;
const w = +(maxX - minX + pad * 2).toFixed(2), h = +(maxY - minY + pad * 2).toFixed(2);
const d = paths.join(' ');
const tx = (-minX + pad).toFixed(2), ty = (-minY + pad).toFixed(2);

// Monogram on a 24 grid: ledger rule (stem) + upward tick that forms the K's arms.
const MARK_PATHS = ['M6.5 4.5v15', 'M13 19.5 7.8 14.5 19 3'];
const markSvg = (stroke = 2.6) => MARK_PATHS.map((p) => `<path d="${p}" fill="none" stroke="currentColor" stroke-width="${stroke}" stroke-linecap="butt" stroke-linejoin="miter"/>`).join('');

mkdirSync('public/brand', { recursive: true });
const wordmark = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" fill="currentColor" role="img" aria-label="Kanakku"><g transform="translate(${tx} ${ty})"><path d="${d}"/></g></svg>\n`;
writeFileSync('public/brand/kanakku-wordmark.svg', wordmark.replace('currentColor', '#1F3A5F'));
// Lockup: mark + wordmark, mark scaled to x-height-ish cap height
const markH = h; // match wordmark height
const scale = markH / 24;
const gap = 0.26 * markH;
const lockW = +(24 * scale + gap + w).toFixed(2);
const lockup = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${lockW} ${h}" role="img" aria-label="Kanakku"><g transform="scale(${scale.toFixed(4)})" color="#1F3A5F">${markSvg()}</g><g transform="translate(${(24 * scale + gap + Number(tx)).toFixed(2)} ${ty})" fill="#1F3A5F"><path d="${d}"/></g></svg>\n`;
writeFileSync('public/brand/kanakku-lockup.svg', lockup);
writeFileSync('public/brand/kanakku-mark.svg', `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" role="img" aria-label="Kanakku" color="#1F3A5F">${markSvg()}</svg>\n`);
// Favicon: white mark on ink-blue tile, heavier stroke for 16px
writeFileSync('public/favicon.svg', `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><rect width="24" height="24" rx="5" fill="#1F3A5F"/><g color="#FFFFFF">${MARK_PATHS.map((p) => `<path d="${p}" fill="none" stroke="currentColor" stroke-width="3" stroke-linecap="butt" stroke-linejoin="miter"/>`).join('')}</g></svg>\n`);
writeFileSync('public/icon.svg', `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><rect width="24" height="24" rx="4.5" fill="#1F3A5F"/><g transform="translate(3.6 3.6) scale(.7)" color="#FFFFFF">${markSvg(3.2)}</g></svg>\n`);

// React component source with the same geometry
const tsx = `/* Generated by scripts/build-logo.mjs — Kanakku wordmark (Inter SemiBold, outlined) and K monogram. */
const WORD_D = '${d}';
export const WORD_VIEW = { w: ${w}, h: ${h}, tx: ${tx}, ty: ${ty} };
export const MARK_PATHS = ${JSON.stringify(MARK_PATHS)};

/** The K monogram: a ledger rule and an upward tick. Single colour (currentColor). */
export function KanakkuMark({ size = 20, stroke = 2.6, title = 'Kanakku' }: { size?: number; stroke?: number; title?: string }) {
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" role="img" aria-label={title} style={{ flexShrink: 0 }}>
      {MARK_PATHS.map((p) => <path key={p} d={p} fill="none" stroke="currentColor" strokeWidth={stroke} strokeLinecap="butt" strokeLinejoin="miter" />)}
    </svg>
  );
}

/** The wordmark as outlined paths, so it renders the same everywhere (including print). */
export function KanakkuWordmark({ height = 16, title = 'Kanakku' }: { height?: number; title?: string }) {
  const width = (WORD_VIEW.w / WORD_VIEW.h) * height;
  return (
    <svg width={width} height={height} viewBox={\`0 0 \${WORD_VIEW.w} \${WORD_VIEW.h}\`} role="img" aria-label={title} fill="currentColor" className="wordmark-text">
      <g transform={\`translate(\${WORD_VIEW.tx} \${WORD_VIEW.ty})\`}><path d={WORD_D} /></g>
    </svg>
  );
}

/** Mark + wordmark lockup used in the sidebar, login and print. */
export function KanakkuLogo({ height = 18 }: { height?: number }) {
  return (
    <span style={{ display: 'inline-flex', alignItems: 'center', gap: height * 0.42, color: 'inherit' }}>
      <KanakkuMark size={height * 1.15} />
      <KanakkuWordmark height={height * 0.86} />
    </span>
  );
}
`;
writeFileSync('src/components/Logo.tsx', tsx);
